// UTC arithmetic on local calendar fields avoids daylight-saving day-length errors.
export function getDailyMessage(date = new Date()) {
  const calendarDay = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
  const anchor = Date.UTC(2026, 0, 1) / 86400000
  const index = ((calendarDay - anchor) % dailyMessages.length + dailyMessages.length) % dailyMessages.length
  return { ...dailyMessages[index], day: index + 1 }
}
